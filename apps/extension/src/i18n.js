  function normalizeLanguage(value) {
    const code = String(value || "").trim().toLowerCase().split(/[-_]/)[0];
    return code === "es" ? "es" : "en";
  }

  function resolveLanguage(stored) {
    return normalizeLanguage(stored || (globalThis.navigator && globalThis.navigator.language));
  }

  function translate(language, key, vars = {}) {
    const table = STRINGS[normalizeLanguage(language)];
    const entry = table[key] ?? STRINGS.en[key] ?? key;
    const template = typeof entry === "string" ? entry : entry[vars.count === 1 ? "one" : "other"];
    return template.replace(/\{(\w+)\}/g, (match, name) => (Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match));
  }

  globalThis.TosDecipherI18n = Object.freeze({ LANGUAGES, normalizeLanguage, resolveLanguage, translate });
